def glyph(char):
    """Return the 7-row bitmap for one character; unknown chars read as '?'."""
    return GLYPHS.get(char, GLYPHS["?"])


def text_width(text, scale=1):
    """Pixel width of text at the given scale (no trailing gap after last char)."""
    if not text:
        return 0
    return len(text) * (GLYPH_W + 1) * scale - scale


def draw_text(canvas, x, y, text, scale=1, color=(0, 0, 0)):
    """Draw text on a canvas (anything with fill_rect) at integer scale."""
    cx = x
    for char in text:
        rows = glyph(char)
        for row_i, row in enumerate(rows):
            for col_i, cell in enumerate(row):
                if cell == "#":
                    canvas.fill_rect(
                        cx + col_i * scale,
                        y + row_i * scale,
                        scale,
                        scale,
                        color,
                    )
        cx += (GLYPH_W + 1) * scale
    return cx


def wrap_text(text, max_width, scale=1):
    """Wrap text on word boundaries so each line fits max_width pixels."""
    lines = []
    current = ""
    for word in text.split(" "):
        trial = word if not current else current + " " + word
        if text_width(trial, scale) <= max_width or not current:
            current = trial
        else:
            lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines
